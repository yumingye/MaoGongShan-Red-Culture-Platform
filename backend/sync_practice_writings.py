def sync_practice_writings(database_path=DB_PATH) -> tuple[int, int]:
    """按标题幂等同步实践文稿，并更新问答知识库。"""

    now = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    inserted = 0
    updated = 0
    with sqlite3.connect(database_path) as conn:
        conn.row_factory = sqlite3.Row
        for entry in PRACTICE_WRITINGS:
            existing = conn.execute(
                "SELECT id FROM research_logs WHERE title = ?", (entry["title"],)
            ).fetchone()
            values = (
                entry["summary"],
                entry["content"],
                entry["category"],
                entry["tags"],
                entry["date"],
                entry["location"],
                entry["image"],
                entry["source"],
                "",
            )
            if existing:
                conn.execute(
                    """
                    UPDATE research_logs
                    SET summary=?, content=?, category=?, tags=?, date=?, location=?,
                        image=?, source=?, related_ids=?
                    WHERE id=?
                    """,
                    (*values, existing["id"]),
                )
                updated += 1
            else:
                conn.execute(
                    """
                    INSERT INTO research_logs (
                        title, summary, content, category, tags, date, location,
                        image, source, related_ids, created_at
                    ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                    """,
                    (
                        entry["title"],
                        entry["summary"],
                        entry["content"],
                        entry["category"],
                        entry["tags"],
                        entry["date"],
                        entry["location"],
                        entry["image"],
                        entry["source"],
                        "",
                        now,
                    ),
                )
                inserted += 1

            knowledge_title = f"实践调研：{entry['title']}"
            knowledge = conn.execute(
                "SELECT id FROM knowledge_documents WHERE title = ?",
                (knowledge_title,),
            ).fetchone()
            knowledge_values = (
                entry["summary"],
                entry["content"],
                entry["category"],
                entry["source"],
                "",
                "实践团队公开展示文稿",
                "",
                "情景化整理稿" if entry["category"] == "访谈整理稿" else "团队公开展示文稿",
                now,
            )
            if knowledge:
                conn.execute(
                    """
                    UPDATE knowledge_documents
                    SET summary=?, content=?, category=?, source_name=?, source_url=?,
                        source_document=?, source_page=?, verification_status=?, updated_at=?
                    WHERE id=?
                    """,
                    (*knowledge_values, knowledge["id"]),
                )
            else:
                conn.execute(
                    """
                    INSERT INTO knowledge_documents (
                        title, summary, content, category, source_name, source_url,
                        source_document, source_page, verification_status,
                        created_at, updated_at
                    ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                    """,
                    (
                        knowledge_title,
                        entry["summary"],
                        entry["content"],
                        entry["category"],
                        entry["source"],
                        "",
                        "实践团队公开展示文稿",
                        "",
                        "情景化整理稿" if entry["category"] == "访谈整理稿" else "团队公开展示文稿",
                        now,
                        now,
                    ),
                )
        conn.commit()
    return inserted, updated


